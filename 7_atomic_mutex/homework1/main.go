// канал:
// канал помогает тем, что горутины передают через него команды,
// а изменяет значение только одна горутина,
// поэтому нет одновременной записи в общую переменную

// принимаем канал ch с целыми числами и кол-во значений count,
// которые нужно получить, и возвращаем int
func number(ch chan int, count int) int {
	votes := 10
	for range count { // i := 0; i < count; i++
		votes += <-ch // получение значения из канала и его прибавление: <-1 or <-2
	}
	return votes // возвращение итогового значения из функции
}

// горутина, принимающая канал и указатель на WG
func inc1(ch chan int, wg *sync.WaitGroup) {
	defer wg.Done() // сообщаем WG о завершении горутины, уменьшаем счетчик WG на 1
	ch <- 1         // отправляем число 1 в канал
}

// горутина, принимающая канал и указатель на WG
func inc2(ch chan int, wg *sync.WaitGroup) {
	defer wg.Done() // сообщаем WG о завершении горутины, счетчик WG -> 0
	ch <- 2         // отправляем число 2 в канал
}

func main() {
	ch := make(chan int) // создаём небуферизованный канал

	wg := &sync.WaitGroup{} // создаём вейтгруппу
	wg.Add(2)

	go inc1(ch, wg)
	go inc2(ch, wg)

	// при вызове number дважды принимает значения из канала и возвращает сумму,
	// получение разблокирует отправки в inc1 и inc2
	votes := number(ch, 2)
	wg.Wait() // ждём пока обе функции-отправителя завершатся и вызовут wg.Done()

	fmt.Println(votes) // 13
}
