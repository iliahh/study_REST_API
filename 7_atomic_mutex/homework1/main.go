/*
Горутина — это функция, запущенная конкурентно с остальной программой.

В Go её запускают ключевым словом go:
Горутины позволяют выполнять несколько задач, не ожидая завершения каждой по очереди.
Они легковесные, а Go сам планирует их выполнение. Конкурентность не гарантирует,
что задачи физически выполняются одновременно — это зависит от среды
и доступных процессорных ядер.

WaitGroup нужен, чтобы дождаться завершения запущенных горутин:
Add вызывают до запуска горутины, Done — когда она завершилась, а Wait блокирует выполнение,
пока счётчик не станет равен нулю.

Важно: WaitGroup только ждёт завершения. Он не защищает общие данные от гонки.
В задании в main.go несколько горутин могут менять votes одновременно — для защиты этой
переменной нужен, например, sync.Mutex, атомарные операции или канал.

*вот такая соба хуйнячка*
*/

