package miner

import (
	"context"
	"fmt"
	"sync"
	"time"
)

/*
шахтёр добывает уголь:
-> transferPoint chan<- - стрелка после chan означает, что у нас отправляется
значение только в сторону канала, и эта функция не сможет его забрать;
-> n - номер шахтёра; power - количество добытого угля.
*/
func miner(
	ctx context.Context,
	wg *sync.WaitGroup,
	transferPoint chan<- int,
	n int, power int,
) {
	defer wg.Done()

	for {
		select {
		case <-ctx.Done():
			fmt.Printf("Я шахтёр №%d, мой рабочий день закончен!\n", n)
			return
		default: // секция в дефаулте выполняется, пока контекст еще не отменён
			fmt.Printf("Я шахтёр №%d, начал добывать уголь!\n", n)
			time.Sleep(1 * time.Second)
			fmt.Printf("Я шахтёр №%d, добыл уголь!\n", n)

			transferPoint <- power
			fmt.Printf("Я шахтёр №%d, передал уголь в количестве %d шт.!\n", n, power)
		}
	}
}

// функция, принимающая количество шахтёров и запускающая сразу
// несколько шахтёров в работу (именуется пулом)
func MinerPool(ctx context.Context, minerCount int) <-chan int {
	// инициализируем канал, который требуют шахтёры для передачи угля
	coalTransferPoint := make(chan int)

	// чтобы дожидаться окончания работы всех шахтёров, воспользуемся WG
	wg := &sync.WaitGroup{}

	for i := 1; i <= minerCount; i++ {
		wg.Add(1)
		go miner(ctx, wg, coalTransferPoint, i, i*10)
	}

	/*
		* короче, если мы запустим наших майнеров и будем дожидаться, когда они завершатся,
		то канал-то мы возвращать будем из наших функций после wg.Wait(),
		то есть получается мы не сможем вернуть наш канал до тех пор пока не завершатся все майнеры,
		а майнеры не завершатся, пока мы не отменим контекст.
		* получается, мы в принципе не сможем вычитать даже значение из нашего канала,
		потому что мы написали, что мы вернем канал,
		только когда все майнеры завершатся - это не правильно!
		* мы хотим возвращать канал сразу же как мы запустили всех наших майнеров,
		чтобы в мейне иметь возможность из этого канала читать, но при этом,
		когда все майнеры завершатся, мы канал хотим закрывать, чтобы в мейне не происходил дедлок,
		и для этого есть решение: выносим ожидание майнеров и закрытие канала в отдельную горутину
	*/
	// wg.Wait()
	// close(coalTransferPoint) // закрываем канал
	go func() {
		wg.Wait()
		close(coalTransferPoint)
	}()

	return coalTransferPoint
}
